#!/usr/bin/env python3
"""Backlog tool for the /scrum and /orchestrate skills.

    scripts/scrum.py snapshot [--json] [--fix-status]
                                              print the backlog digest
    scripts/scrum.py apply PLAN.json [--dry-run]
                                              apply the agreed plan
    scripts/scrum.py links [--apply]         add the blocked-by links that
                                              the "Depends on" texts name
    scripts/scrum.py labels                  create the missing labels

Needs only python3 and an authenticated `gh`. It uses the REST API
(`gh api`), because GraphQL is not available in cloud sessions. Set
SCRUM_REPO to change the repository (default revslaughter/aug-blog).

Plan file (JSON), one entry per issue. Every key except "issue" is optional:

    {"issues": [
      {"issue": 80, "priority": "p1", "comment": "Next after the calendar fix."},
      {"issue": 69, "add": ["icebox"], "remove": ["enhancement"]},
      {"issue": 51, "close": "not_planned", "comment": "Done by hand."},
      {"issue": 66, "blocked_by": [79]},
      {"issue": 78, "priority": "p0",
       "wp": {"model": "sonnet", "body": "## Goal\\n...\\n## Out of scope\\n..."}}
    ]}

"priority" is p0, p1, p2, or p3 (or "none" to clear it). The repository
already used the labels `priority: high`, `priority: medium`, and
`priority: low`, so the levels map onto them:

    p0 -> priority: critical   do now
    p1 -> priority: high       next
    p2 -> priority: medium     later
    p3 -> priority: low        someday

Setting a priority removes the other priority labels. "close" is
"completed" or "not_planned".

"blocked_by" lists issue numbers that block this issue; `apply` adds each
missing blocked-by link. A "wp" conversion also links the open blockers
that its "Depends on" section names. The links are the dependencies
(docs/agentic-development.md section 2.2).

"wp" turns a non-WP issue into a work package in place: the title gets the
next free `[WP-NN]` prefix, the body becomes the WP sections followed by the
original text under "## Original report", and the labels `wp` and
`model:<model>` are added. The body must have every WP section
(docs/agentic-development.md section 2.1).

The snapshot ends with the orchestrator's state: each open WP as blocked,
ready, in progress, in review (with its PR), or escalated, and each
`status:*` label that disagrees. Only /orchestrate owns `status:*` labels,
so only it passes --fix-status, which sets the label that the snapshot
computed. Two cases need a person, and the flag leaves them alone:
`status:in-review` with no open PR, and `status:in-progress` (the snapshot
cannot see a running agent).

Dependencies are GitHub's blocked-by links. A WP is blocked while one of
its blockers is open; a closed blocker no longer blocks, whatever the close
reason. A WP with no links falls back to its "Depends on" text, and is
flagged until `links --apply` adds the links that the text names. When
links and text disagree, the links win and the row is flagged. In the
text, a pull request ("PR #97") does not count, and a number that is not
an issue is flagged.

`apply` refuses `status:*` labels (they belong to /orchestrate) and label
names that do not exist. A run that stops part way can be run again: labels,
closes, and WP conversions are idempotent, and a comment that is already on
the issue is not posted twice.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import urllib.parse
from datetime import datetime, timezone

REPO = os.environ.get("SCRUM_REPO", "revslaughter/aug-blog")
STALE_DAYS = 30
MARKER = "<!-- scrum -->"
FOOTER = "\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"

PRIORITY = {
    "p0": ("priority: critical", "b60205", "Do now: it blocks other work or the site"),
    "p1": ("priority: high", "d93f0b", "Next up: start when a slot is free"),
    "p2": ("priority: medium", "fbca04", "Later: planned, not next"),
    "p3": ("priority: low", "c2e0c6", "Someday: wanted, no plan"),
}
ICEBOX = ("icebox", "bfd4f2", "Parked on purpose: not in the active backlog")
OWN_LABELS = list(PRIORITY.values()) + [ICEBOX]
MODELS = ("haiku", "sonnet", "opus")  # docs/agentic-development.md section 9
WP_SECTIONS = ("Goal", "Depends on", "Owned files", "Acceptance criteria",
               "Notes", "Out of scope")
KIND_ORDER = ["wp", "bug", "enhancement", "other", "epic", "ops"]
# Kinds that may become a WP. Epics and ops notices (the ci:billing issue of
# /orchestrate) may not.
CANDIDATE_KINDS = ("bug", "enhancement", "other")

# An issue ID such as WP-12, WP-06a, or Fix-3.
ID = r"[A-Za-z]+-\d+[a-z]?"
TITLE_ID = re.compile(rf"\[({ID})\]")
DEP_ID = re.compile(rf"(?<![\w/.-])({ID})(?![\w-])")
# A pull request named in a "Depends on" line, as in "from the tests, PR #697".
PR_REF = re.compile(r"\b(?:PR|pull request)\s+#\d+", re.I)
STATUSES = ("blocked", "ready", "in-progress", "in-review", "escalated")


def gh(*args, stdin=None):
    """Run `gh` and return stdout. Exit with a clear message on failure."""
    proc = subprocess.run(
        ["gh", *args], input=stdin, capture_output=True, text=True
    )
    if proc.returncode != 0:
        sys.exit(f"gh {' '.join(args[:3])} failed: {proc.stderr.strip()}")
    return proc.stdout


def pages(path):
    """All items of a list endpoint. Pages by hand: `gh --paginate` follows
    numeric-ID links that the cloud proxy refuses."""
    sep = "&" if "?" in path else "?"
    items, page = [], 1
    while True:
        chunk = json.loads(gh("api", f"repos/{REPO}/{path}{sep}per_page=100&page={page}"))
        items += chunk
        if len(chunk) < 100:
            return items
        page += 1


def api(path, method="GET", body=None):
    args = ["api", f"repos/{REPO}/{path}", "-X", method]
    if body is not None:
        args += ["--input", "-"]
    out = gh(*args, stdin=json.dumps(body) if body is not None else None)
    return json.loads(out) if out.strip() else None


def fetch_issues():
    """Every issue (open and closed). Pull requests are dropped."""
    return [i for i in pages("issues?state=all") if "pull_request" not in i]


def fetch_open_prs():
    return pages("pulls?state=open")


def days_since(stamp):
    then = datetime.fromisoformat(stamp.replace("Z", "+00:00"))
    return (datetime.now(timezone.utc) - then).days


def kind_of(issue, labels):
    title = issue["title"]
    if "ci:billing" in labels or title.startswith("[ops]"):
        return "ops"
    if "wp" in labels:
        return "wp"
    if "epic" in labels:
        return "epic"
    if "bug" in labels or title.lower().startswith("[bug]"):
        return "bug"
    if "enhancement" in labels:
        return "enhancement"
    return "other"


def section(body, name):
    """The text under a `## name` or `### name` heading, or None."""
    m = re.search(rf"^#{{2,3}}\s+{re.escape(name)}\s*$", body or "", re.M | re.I)
    if not m:
        return None
    rest = body[m.end():]
    nxt = re.search(r"^#{2,3}\s", rest, re.M)
    return rest[: nxt.start()] if nxt else rest


def title_id(title):
    m = TITLE_ID.match(title)
    return m.group(1).upper() if m else None


def next_wp_number(issues):
    nums = [int(m.group(1)) for i in issues
            if (m := re.match(r"\[WP-(\d+)[a-z]?\]", i["title"]))]
    return max(nums, default=0) + 1


def fetch_links(issues):
    """{number: [blocker issue]} for each open WP that has blocked-by links.
    The issue list carries a summary; only linked issues need a call."""
    out = {}
    for i in issues:
        summary = i.get("issue_dependencies_summary") or {}
        if i["state"] == "open" and summary.get("total_blocked_by"):
            out[i["number"]] = pages(f"issues/{i['number']}/dependencies/blocked_by")
    return out


def id_index(issues):
    """{WP ID: issue number}. The list is newest first. Walk it oldest
    first, so that a reused ID resolves to the newest issue that has it."""
    by_id = {}
    for i in reversed(issues):
        tid = title_id(i["title"])
        if tid:
            by_id[tid] = i["number"]
    return by_id


def text_deps(issue, by_id):
    """(numbers, unknown IDs) named in the "Depends on" section."""
    text = PR_REF.sub("", section(issue["body"], "Depends on") or "")
    nums = {int(n) for n in re.findall(r"#(\d+)", text)}
    unknown = []
    for ref in DEP_ID.findall(text):
        if ref.upper() in by_id:
            nums.add(by_id[ref.upper()])
        else:
            unknown.append(ref)
    nums.discard(issue["number"])
    return nums, unknown


def build(issues, links=None):
    """One row for each issue, with the computed fields.

    The blocked-by links of GitHub decide readiness: a WP is blocked while
    one of its blockers is open. A closed blocker no longer blocks, whatever
    the close reason (GitHub's rule). A WP with no links falls back to its
    "Depends on" text, with a flag, until `scrum.py links --apply` adds them.
    When both exist and disagree, the row is flagged."""
    links = links or {}
    by_id = id_index(issues)
    by_num = {i["number"]: i for i in issues}

    rows = []
    for i in issues:
        labels = {lab["name"] for lab in i["labels"]}
        row = {
            "number": i["number"],
            "title": i["title"],
            "state": i["state"],
            "state_reason": i.get("state_reason"),
            "labels": sorted(labels),
            "kind": kind_of(i, labels),
            "age": days_since(i["created_at"]),
            "idle": days_since(i["updated_at"]),
            "comments": i["comments"],
            "priority": next(
                (k for k, v in PRIORITY.items() if v[0] in labels), None
            ),
            "icebox": "icebox" in labels,
            "needs_human": "needs-human" in labels,
            "deps": [],
            "text_deps": [],
            "linked": False,
            "open_deps": [],
            "unknown_deps": [],
            "flags": [],
        }
        if row["state"] == "open" and row["kind"] == "wp":
            nums, unknown = text_deps(i, by_id)
            row["unknown_deps"] = unknown
            known = set()
            for n in sorted(nums):
                if n in by_num:
                    known.add(n)
                else:
                    row["unknown_deps"].append(f"#{n}")
            row["text_deps"] = sorted(known)
            if i["number"] in links:
                blockers = links[i["number"]]
                row["linked"] = True
                row["deps"] = sorted(b["number"] for b in blockers)
                row["open_deps"] = sorted(b["number"] for b in blockers if b["state"] == "open")
                # Compare open blockers only: a closed one blocks nothing,
                # and prose names closed issues as history ("from the Mod-4
                # tests").
                text_open = {n for n in known if by_num[n]["state"] == "open"}
                if set(row["open_deps"]) != text_open:
                    row["flags"].append(
                        "links and text disagree on open blockers: links "
                        + (",".join(f"#{n}" for n in row["open_deps"]) or "none")
                        + "; text " + (",".join(f"#{n}" for n in sorted(text_open)) or "none"))
            else:
                row["deps"] = sorted(known)
                row["open_deps"] = [n for n in row["deps"] if by_num[n]["state"] == "open"]
                if row["open_deps"]:
                    row["flags"].append("no blocked-by links (run scrum.py links)")
            for need in ("Acceptance criteria", "Owned files"):
                if section(i["body"], need) is None:
                    row["flags"].append(f"no '{need}' section")
        rows.append(row)
    return rows


def link_plan(rows, by_num):
    """[(wp number, blocker number)] of the links to open blockers that the
    "Depends on" text names and GitHub lacks. A closed blocker gets no link:
    it blocks nothing, and prose often names closed issues as history. Links
    that the text does not name stay: the links win, and the snapshot flags
    the difference."""
    plan = []
    for r in rows:
        if r["state"] == "open" and r["kind"] == "wp":
            have = set(r["deps"]) if r["linked"] else set()
            plan += [(r["number"], n) for n in r["text_deps"]
                     if n not in have and by_num[n]["state"] == "open"]
    return plan


def open_pr_of(row, prs):
    """The number of the open PR that names this issue (a `Closes #N` line,
    or the issue's [ID] at the start of the PR title), or None."""
    tid = title_id(row["title"])
    closes = re.compile(rf"^Closes #{row['number']}\b", re.M)
    for p in prs:
        if closes.search(p.get("body") or ""):
            return p["number"]
        if tid and title_id(p["title"]) == tid:
            return p["number"]
    return None


def in_open_pr(row, prs):
    return open_pr_of(row, prs) is not None


def status_of(row):
    """(state, expected label or None, note) for an open WP. The label is
    None when only a person can decide."""
    have = [l.split(":", 1)[1] for l in row["labels"] if l.startswith("status:")]
    if "escalated" in have:
        return "escalated", "escalated", ""
    if row.get("pr"):
        return "in-review", "in-review", f"PR #{row['pr']}"
    if "in-review" in have:
        return "in-review", None, "status:in-review but no open PR"
    if "in-progress" in have:
        return "in-progress", "in-progress", ""
    if row["open_deps"]:
        return "blocked", "blocked", ""
    return "ready", "ready", ""


def finish_flags(rows, prs):
    for r in rows:
        if r["state"] != "open":
            continue
        if r["kind"] not in ("epic", "ops") and not r["icebox"] \
                and not r["priority"]:
            r["flags"].append("no priority")
        if r["idle"] > STALE_DAYS:
            r["flags"].append(f"idle {r['idle']}d")
        if r["kind"] == "wp":
            if r["unknown_deps"]:
                r["flags"].append("unknown deps: " + ", ".join(r["unknown_deps"]))
            r["readiness"] = "blocked" if r["open_deps"] else "ready"
            r["pr"] = open_pr_of(r, prs)
            if r["pr"]:
                r["readiness"] = "in PR"
            for s in ("status:in-progress", "status:in-review", "status:escalated"):
                if s in r["labels"]:
                    r["readiness"] = s.split(":")[1]
            if not r["icebox"]:
                state, want, note = status_of(r)
                have = sorted(l for l in r["labels"] if l.startswith("status:"))
                r["wp_state"] = state
                r["status_note"] = note
                r["status_fix"] = None
                if want is None:
                    r["flags"].append(note)
                elif have != [f"status:{want}"]:
                    r["status_fix"] = f"status:{want}"
                    r["flags"].append(f"label should be status:{want}"
                                      + (f" (has {', '.join(have)})" if have else ""))


def prio_key(r):
    p = r["priority"]
    return (p if p else "p9", r["number"])


def fmt_row(r):
    pr = r["priority"] or "--"
    bits = []
    if r["kind"] == "wp":
        extra = r.get("readiness", "")
        if r["open_deps"]:
            extra += " on " + ",".join(f"#{n}" for n in r["open_deps"])
        bits.append(extra)
    if r["needs_human"]:
        bits.append("needs-human")
    if r["icebox"]:
        bits.append("icebox")
    bits += r["flags"]
    note = f"  [{'; '.join(b for b in bits if b)}]" if bits else ""
    return f"  {pr:>3}  #{r['number']:<4} {r['title'][:88]}{note}"


def is_candidate(r):
    return r["state"] == "open" and r["kind"] in CANDIDATE_KINDS \
        and not r["icebox"]


def cmd_snapshot(args):
    issues = fetch_issues()
    rows = build(issues, fetch_links(issues))
    prs = fetch_open_prs()
    finish_flags(rows, prs)
    open_rows = [r for r in rows if r["state"] == "open"]
    next_wp = next_wp_number(issues)

    if args.json:
        if args.fix_status:
            fix_status(open_rows, out=sys.stderr)
        json.dump(
            {"repo": REPO, "next_wp": next_wp, "open": open_rows,
             "open_prs": [{"number": p["number"], "title": p["title"],
                           "draft": p["draft"], "base": p["base"]["ref"],
                           "idle": days_since(p["updated_at"])} for p in prs]},
            sys.stdout, indent=1)
        print()
        return

    closed = sorted(
        (i for i in issues if i["state"] == "closed" and i.get("closed_at")),
        key=lambda i: i["closed_at"], reverse=True)
    print(f"# Backlog digest for {REPO}: {len(open_rows)} open issues, "
          f"{len(prs)} open PRs\n")

    print("## Open PRs")
    for p in prs:
        print(f"  #{p['number']:<4} {p['title'][:80]}  -> {p['base']['ref']}"
              f"{' (draft)' if p['draft'] else ''}, idle {days_since(p['updated_at'])}d")
    if not prs:
        print("  none")

    print("\n## Closed in the last 7 days")
    recent = [i for i in closed if days_since(i["closed_at"]) <= 7]
    for i in recent[:15]:
        print(f"  #{i['number']:<4} {i['title'][:88]}")
    if not recent:
        print("  none")

    for kind in KIND_ORDER:
        group = sorted((r for r in open_rows if r["kind"] == kind and not r["icebox"]),
                       key=prio_key)
        if group:
            print(f"\n## {kind} ({len(group)})")
            for r in group:
                print(fmt_row(r))

    ice = [r for r in open_rows if r["icebox"]]
    if ice:
        print(f"\n## icebox ({len(ice)})")
        for r in sorted(ice, key=prio_key):
            print(fmt_row(r))

    cands = sorted((r for r in open_rows if is_candidate(r)), key=prio_key)
    print(f"\n## WP candidates (not WPs yet; /orchestrate cannot start them). "
          f"Next WP number: WP-{next_wp}")
    for r in cands:
        print(fmt_row(r))
    if not cands:
        print("  none")

    ready = sorted((r for r in open_rows
                    if r["kind"] == "wp" and r.get("readiness") == "ready"
                    and not r["icebox"]), key=prio_key)
    print("\n## Orchestrate queue (ready WPs, by priority then number)")
    for r in ready:
        print(fmt_row(r))
    if not ready:
        print("  none")

    print_state(open_rows)
    if args.fix_status:
        fix_status(open_rows)

    unprio = [r for r in open_rows if "no priority" in r["flags"]]
    stale = [r for r in open_rows if any(f.startswith("idle") for f in r["flags"])]
    other = [r for r in open_rows
             if any(not f.startswith("idle") and f != "no priority" for f in r["flags"])]
    hot = [r for r in cands if r["priority"] in ("p0", "p1")]
    print(f"\n## Totals"
          f"\n  without priority: {len(unprio)}"
          f"\n  p0 or p1 but not a WP: {len(hot)}"
          f"\n  idle over {STALE_DAYS} days: {len(stale)}"
          f"\n  with other flags: {len(other)}")


def print_state(open_rows):
    """The orchestrator's state (the /orchestrate runbook, section 1)."""
    wps = [r for r in open_rows if r["kind"] == "wp" and "wp_state" in r]
    print("\n## Orchestrate state (open WPs, icebox left out)")
    for state in reversed(STATUSES):
        group = sorted((r for r in wps if r["wp_state"] == state), key=prio_key)
        if not group:
            continue
        print(f"  {state} ({len(group)})")
        for r in group:
            tid = title_id(r["title"]) or "?"
            extra = ""
            if r.get("pr"):
                extra = f"  PR #{r['pr']}"
            elif state == "blocked":
                extra = "  on " + ",".join(f"#{n}" for n in r["open_deps"])
            print(f"    {r['priority'] or '--':>3}  #{r['number']:<4} {tid:<10}{extra}")
    fixes = [r for r in wps if r.get("status_fix")]
    judge = [r for r in wps if r.get("status_note") and not r.get("status_fix")
             and r["wp_state"] == "in-review" and not r.get("pr")]
    print("  status labels to fix" + ("" if fixes else ": none"))
    for r in fixes:
        have = ", ".join(l for l in r["labels"] if l.startswith("status:")) or "none"
        print(f"    #{r['number']:<4} {have} -> {r['status_fix']}")
    for r in judge:
        print(f"    #{r['number']:<4} {r['status_note']}: decide by hand")


def fix_status(open_rows, out=sys.stdout):
    """Set the computed status:* label on each WP whose label disagrees.
    Only /orchestrate runs this."""
    for r in open_rows:
        want = r.get("status_fix")
        if not want:
            continue
        n = r["number"]
        api(f"issues/{n}/labels", "POST", {"labels": [want]})
        for lab in r["labels"]:
            if lab.startswith("status:") and lab != want:
                api(f"issues/{n}/labels/{urllib.parse.quote(lab, safe='')}", "DELETE")
        print(f"#{n}: {want}", file=out)


def cmd_links(args):
    """Add the blocked-by links that the "Depends on" texts name."""
    issues = fetch_issues()
    by_num = {i["number"]: i for i in issues}
    rows = build(issues, fetch_links(issues))
    plan = link_plan(rows, by_num)
    for wp, dep in plan:
        d = by_num[dep]
        state = d["state"] + (f", {d['state_reason']}" if d.get("state_reason") else "")
        print(f"#{wp:<4} {title_id(by_num[wp]['title']) or '':<9} blocked by "
              f"#{dep:<4} {title_id(d['title']) or d['title'][:30]} ({state})")
    if not plan:
        print("every link that the texts name exists")
        return
    print(f"{len(plan)} link(s)" + ("" if args.apply else " (dry run; --apply adds them)"))
    if not args.apply:
        return
    failed = 0
    for wp, dep in plan:
        # The API takes the blocker's internal id, not its number.
        proc = subprocess.run(
            ["gh", "api", "-X", "POST", f"repos/{REPO}/issues/{wp}/dependencies/blocked_by",
             "-F", f"issue_id={by_num[dep]['id']}"], capture_output=True, text=True)
        if proc.returncode:
            failed += 1
            print(f"#{wp} <- #{dep}: {proc.stderr.strip() or proc.stdout.strip()}")
    # Read back from the list, not the summary: the summary lags by seconds.
    for wp in sorted({wp for wp, _ in plan}):
        have = {b["number"] for b in pages(f"issues/{wp}/dependencies/blocked_by")}
        missing = [dep for w, dep in plan if w == wp and dep not in have]
        if missing:
            failed += 1
            print(f"#{wp}: still missing " + ", ".join(f"#{n}" for n in missing))
    print("all links added" if not failed else f"{failed} problem(s)")
    sys.exit(1 if failed else 0)


def ensure_labels(wanted):
    have = {l["name"] for l in pages("labels")}
    made = []
    for name, color, desc in wanted:
        if name not in have:
            api("labels", "POST",
                {"name": name, "color": color, "description": desc})
            made.append(name)
    return made


def cmd_labels(_args):
    made = ensure_labels(OWN_LABELS)
    print("created: " + ", ".join(made) if made else "all labels exist")


def validate(entries, known_labels):
    """Return a list of errors in the plan. An empty list means valid."""
    errs = []
    known = set(known_labels) | {v[0] for v in OWN_LABELS}
    seen = set()
    for e in entries:
        n = e.get("issue")
        if not isinstance(n, int):
            errs.append(f"entry without an integer 'issue': {e}")
            continue
        if n in seen:
            errs.append(f"#{n}: listed twice; merge the entries")
        seen.add(n)
        extra = set(e) - {"issue", "priority", "comment", "add", "remove",
                          "close", "wp", "blocked_by"}
        if extra:
            errs.append(f"#{n}: unknown keys {sorted(extra)}")
        if e.get("priority") not in (None, "none", *PRIORITY):
            errs.append(f"#{n}: bad priority {e['priority']!r}")
        deps = e.get("blocked_by", [])
        if not isinstance(deps, list) or not all(isinstance(d, int) for d in deps):
            errs.append(f"#{n}: blocked_by must be a list of issue numbers")
        elif n in deps:
            errs.append(f"#{n}: an issue cannot block itself")
        if e.get("close") not in (None, "completed", "not_planned"):
            errs.append(f"#{n}: bad close {e['close']!r}")
        for lab in e.get("add", []) + e.get("remove", []):
            if lab.startswith("status:"):
                errs.append(f"#{n}: {lab} belongs to /orchestrate")
            elif lab not in known:
                errs.append(f"#{n}: no label named {lab!r}")
        wp = e.get("wp")
        if wp is not None:
            if e.get("close"):
                errs.append(f"#{n}: cannot both close and convert to a WP")
            if wp.get("model") not in MODELS:
                errs.append(f"#{n}: wp.model must be one of {MODELS}")
            if wp.get("model") == "haiku" and "needs-human" in e.get("add", []):
                errs.append(f"#{n}: a needs-human WP cannot be haiku (section 9)")
            missing = [s for s in WP_SECTIONS
                       if section(wp.get("body", ""), s) is None]
            if missing:
                errs.append(f"#{n}: wp.body lacks sections {missing}")
    return errs


def wp_change(issue, wp, number):
    """The new title and body for a WP conversion, or None if the issue is
    already a WP."""
    if title_id(issue["title"]) or any(l["name"] == "wp" for l in issue["labels"]):
        return None
    # Drop a leading tag such as [bug]. The label keeps the kind.
    title = f"[WP-{number}] " + re.sub(r"^\[[^\]]*\]\s*", "", issue["title"])
    body = wp["body"].strip()
    old = (issue.get("body") or "").strip()
    if old:
        body += "\n\n## Original report\n\n" + old
    return title, body


def cmd_apply(args):
    with open(args.plan) as f:
        plan = json.load(f)
    entries = plan["issues"]

    errs = validate(entries, [l["name"] for l in pages("labels")])
    issues = {}
    for e in entries:
        if isinstance(e.get("issue"), int):
            issues[e["issue"]] = api(f"issues/{e['issue']}")
    if errs:
        sys.exit("plan refused:\n  " + "\n  ".join(errs))

    if not args.dry_run:
        made = ensure_labels(OWN_LABELS)
        if made:
            print("created labels: " + ", ".join(made))

    everything = fetch_issues() if any("wp" in e or "blocked_by" in e for e in entries) else []
    by_num = {i["number"]: i for i in everything}
    by_id = id_index(everything)
    unknown = [f"#{e['issue']}: blocked_by #{d} is not an issue"
               for e in entries for d in e.get("blocked_by", []) if d not in by_num]
    if unknown:
        sys.exit("plan refused:\n  " + "\n  ".join(unknown))
    next_wp = next_wp_number(everything) if any("wp" in e for e in entries) else 0
    for e in entries:
        n = e["issue"]
        issue = issues[n]
        have = {l["name"] for l in issue["labels"]}
        want = set(have)
        if "priority" in e:
            want -= {v[0] for v in PRIORITY.values()}
            if e["priority"] != "none":
                want.add(PRIORITY[e["priority"]][0])
        want |= set(e.get("add", []))
        want -= set(e.get("remove", []))

        conv = wp_change(issue, e["wp"], next_wp) if e.get("wp") else None
        if conv:
            want |= {"wp", f"model:{e['wp']['model']}"}
            next_wp += 1

        # Blocked-by links (docs/agentic-development.md section 2.2): the
        # plan's list, and for a new WP the open blockers its text names.
        links = set(e.get("blocked_by", []))
        if conv:
            named, _ = text_deps({"number": n, "body": conv[1]}, by_id)
            links |= {d for d in named if d in by_num and by_num[d]["state"] == "open"}
        if links:
            links -= {b["number"] for b in pages(f"issues/{n}/dependencies/blocked_by")}

        comment = None
        if e.get("comment"):
            comment = MARKER + "\n" + e["comment"].strip() + FOOTER
            if issue["comments"] and any(
                    c["body"] == comment for c in pages(f"issues/{n}/comments")):
                comment = None

        actions = []
        if conv:
            actions.append(f"title -> {conv[0][:60]!r}; WP body")
        if want != have:
            actions.append("labels +" + ",".join(sorted(want - have))
                           + " -" + ",".join(sorted(have - want)))
        if links:
            actions.append("blocked by " + ",".join(f"#{d}" for d in sorted(links)))
        if comment:
            actions.append("comment")
        if e.get("close") and issue["state"] == "open":
            actions.append("close " + e["close"])
        if not actions:
            print(f"#{n}: no change")
            continue
        print(f"#{n}: " + "; ".join(actions) + (" (dry run)" if args.dry_run else ""))
        if args.dry_run:
            continue

        if conv:
            api(f"issues/{n}", "PATCH", {"title": conv[0], "body": conv[1]})
        # Add and remove one by one, not PUT the whole set: a PUT would undo a
        # status:* change that /orchestrate made since the read above.
        if want - have:
            api(f"issues/{n}/labels", "POST", {"labels": sorted(want - have)})
        for lab in sorted(have - want):
            api(f"issues/{n}/labels/{urllib.parse.quote(lab, safe='')}", "DELETE")
        for d in sorted(links):
            # The API takes the blocker's internal id, not its number.
            api(f"issues/{n}/dependencies/blocked_by", "POST", {"issue_id": by_num[d]["id"]})
        if comment:
            api(f"issues/{n}/comments", "POST", {"body": comment})
        if e.get("close") and issue["state"] == "open":
            api(f"issues/{n}", "PATCH",
                {"state": "closed", "state_reason": e["close"]})


